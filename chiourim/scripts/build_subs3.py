def fmt(t, sep):
    h = int(t // 3600)
    m = int((t % 3600) // 60)
    s = int(t % 60)
    ms = int(round((t - int(t)) * 1000))
    if ms == 1000:
        s += 1; ms = 0
    return f"{h:02d}:{m:02d}:{s:02d}{sep}{ms:03d}"

srt, vtt = [], ["WEBVTT", ""]
for i, (start, text) in enumerate(cues):
    end = cues[i+1][0] if i+1 < len(cues) else VIDEO_END
    assert end > start, f"cue {i+1}: end <= start"
    srt.append(str(i+1))
    srt.append(f"{fmt(start,',')} --> {fmt(end,',')}")
    srt.append(text)
    srt.append("")
    vtt.append(f"{fmt(start,'.')} --> {fmt(end,'.')}")
    vtt.append(text)
    vtt.append("")

open("chiour3_fr.srt", "w", encoding="utf-8").write("\n".join(srt))
open("chiour3_fr.vtt", "w", encoding="utf-8").write("\n".join(vtt))
